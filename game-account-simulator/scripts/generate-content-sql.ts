/**
 * Generates the content + world migrations from src/content (single source of truth).
 *   npm run gen:content
 * Output is deterministic; re-running produces byte-identical files.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { CATALOG, ITEM_SETS } from '../src/content/catalog';
import { GAMES, GAME_PASSES } from '../src/content/games';
import { ACHIEVEMENTS, QUESTS } from '../src/content/progression';
import { buildWorld } from '../src/content/world';

const OUT = join(__dirname, '..', 'supabase', 'migrations');

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const ago = (days: number) => `now() - interval '${days} days'`;
const agoMin = (minutes: number) => `now() - interval '${minutes} minutes'`;
const arr = (v: string[]) => (v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`);

function rows(table: string, cols: string[], values: string[][], conflict: string): string {
  if (!values.length) return '';
  const chunks: string[] = [];
  for (let i = 0; i < values.length; i += 200) {
    const part = values.slice(i, i + 200).map((v) => `  (${v.join(', ')})`).join(',\n');
    chunks.push(`insert into public.${table} (${cols.join(', ')}) values\n${part}\n${conflict};\n`);
  }
  return chunks.join('\n');
}

// ── Content ────────────────────────────────────────────────────────────────
let content = `-- GENERATED by scripts/generate-content-sql.ts from src/content — do not edit by hand.
-- Blockora content: item sets, catalog, games, passes, achievements, quests.
-- Upserts, so re-running a newer version updates content in place.

`;
content += rows('item_sets', ['key', 'name', 'description', 'reward_orbs', 'sort_order'],
  ITEM_SETS.map((s) => [q(s.key), q(s.name), q(s.description), q(s.rewardOrbs), q(s.sortOrder)]),
  'on conflict (key) do update set name = excluded.name, description = excluded.description, reward_orbs = excluded.reward_orbs, sort_order = excluded.sort_order');

content += '\n' + rows('catalog_items',
  ['id', 'name', 'description', 'slot', 'rarity', 'price', 'is_for_sale', 'is_limited', 'stock_total', 'stock_remaining',
    'season_key', 'set_key', 'is_starter', 'featured', 'creator_name', 'asset', 'tags', 'sales_count', 'favorites_count', 'created_at'],
  CATALOG.map((c) => {
    const sales = c.limited ? c.limited.sold : (c.baseSales ?? 0);
    return [q(c.id), q(c.name), q(c.description), `${q(c.slot)}::public.item_slot`, `${q(c.rarity)}::public.item_rarity`,
      q(c.price), q(c.forSale ?? true), q(!!c.limited), q(c.limited?.stock ?? null),
      q(c.limited ? c.limited.stock - c.limited.sold : null), q(c.seasonKey ?? null), q(c.setKey ?? null),
      q(!!c.starter), q(!!c.featured), q(c.creator ?? 'Blockora Studio'), j(c.asset), arr(c.tags ?? []),
      q(sales), q(Math.round(sales * 0.18)), ago(c.ageDays)];
  }),
  `on conflict (id) do update set name = excluded.name, description = excluded.description, slot = excluded.slot,
  rarity = excluded.rarity, price = excluded.price, is_for_sale = excluded.is_for_sale, season_key = excluded.season_key,
  set_key = excluded.set_key, is_starter = excluded.is_starter, featured = excluded.featured,
  creator_name = excluded.creator_name, asset = excluded.asset, tags = excluded.tags`);

content += '\n' + rows('games',
  ['id', 'title', 'tagline', 'description', 'genre', 'engine', 'config', 'thumbnail', 'creator_name', 'score_per_orb',
    'max_orbs_per_session', 'daily_orb_cap', 'max_score_per_second', 'score_grace', 'xp_per_play', 'visits', 'likes',
    'dislikes', 'favorites', 'base_ccu', 'trend_seed', 'featured', 'sort_order', 'created_at', 'updated_at'],
  GAMES.map((g) => [q(g.id), q(g.title), q(g.tagline), q(g.description), q(g.genre), q(g.engine), j(g.config), j(g.thumbnail),
    q(g.creator), q(g.scorePerOrb), q(g.maxOrbsPerSession), q(g.dailyOrbCap), q(g.maxScorePerSecond), q(g.scoreGrace),
    q(g.xpPerPlay), q(g.baseVisits), q(g.baseLikes), q(g.baseDislikes), q(g.baseFavorites), q(g.baseCcu), q(g.trendSeed),
    q(!!g.featured), q(g.sortOrder), ago(g.ageDays), ago(Math.max(1, Math.floor(g.ageDays / 6)))]),
  `on conflict (id) do update set title = excluded.title, tagline = excluded.tagline, description = excluded.description,
  genre = excluded.genre, engine = excluded.engine, config = excluded.config, thumbnail = excluded.thumbnail,
  creator_name = excluded.creator_name, score_per_orb = excluded.score_per_orb, max_orbs_per_session = excluded.max_orbs_per_session,
  daily_orb_cap = excluded.daily_orb_cap, max_score_per_second = excluded.max_score_per_second, score_grace = excluded.score_grace,
  xp_per_play = excluded.xp_per_play, base_ccu = excluded.base_ccu, trend_seed = excluded.trend_seed,
  featured = excluded.featured, sort_order = excluded.sort_order`);

content += '\n' + rows('game_passes',
  ['id', 'game_id', 'name', 'description', 'price', 'perk_type', 'perk_value', 'icon', 'sales_count'],
  GAME_PASSES.map((p) => [q(p.id), q(p.gameId), q(p.name), q(p.description), q(p.price), q(p.perkType), q(p.perkValue),
    j(p.icon), q(p.baseSales)]),
  `on conflict (id) do update set name = excluded.name, description = excluded.description, price = excluded.price,
  perk_type = excluded.perk_type, perk_value = excluded.perk_value, icon = excluded.icon`);

content += '\n' + rows('achievements',
  ['key', 'name', 'description', 'icon', 'category', 'metric', 'target', 'engine', 'reward_orbs', 'reward_xp', 'is_secret', 'sort_order'],
  ACHIEVEMENTS.map((a) => [q(a.key), q(a.name), q(a.description), q(a.icon), q(a.category), q(a.metric), q(a.target),
    q(a.engine ?? null), q(a.rewardOrbs), q(a.rewardXp), q(!!a.isSecret), q(a.sortOrder)]),
  `on conflict (key) do update set name = excluded.name, description = excluded.description, icon = excluded.icon,
  category = excluded.category, metric = excluded.metric, target = excluded.target, engine = excluded.engine,
  reward_orbs = excluded.reward_orbs, reward_xp = excluded.reward_xp, is_secret = excluded.is_secret, sort_order = excluded.sort_order`);

content += '\n' + rows('quests',
  ['key', 'title', 'description', 'goal_type', 'target', 'reward_orbs', 'reward_xp', 'sort_order'],
  QUESTS.map((x) => [q(x.key), q(x.title), q(x.description), q(x.goalType), q(x.target), q(x.rewardOrbs), q(x.rewardXp), q(x.sortOrder)]),
  `on conflict (key) do update set title = excluded.title, description = excluded.description, goal_type = excluded.goal_type,
  target = excluded.target, reward_orbs = excluded.reward_orbs, reward_xp = excluded.reward_xp, sort_order = excluded.sort_order`);

writeFileSync(join(OUT, '20261114000009_content.sql'), content);

// ── World ──────────────────────────────────────────────────────────────────
const w = buildWorld();
let world = `-- GENERATED by scripts/generate-content-sql.ts from src/content/world.ts — do not edit by hand.
-- The simulated Blockora community: ${w.npcs.length} NPC players with avatars, inventories,
-- game stats, social graph and recent activity. NPCs have no auth account and cannot sign in.

`;
world += rows('profiles',
  ['id', 'username', 'display_name', 'bio', 'status_text', 'profile_theme', 'level', 'xp', 'reputation', 'is_npc', 'created_at', 'last_seen_at'],
  w.npcs.map((n) => [q(n.id), q(n.username), q(n.display_name), q(n.bio), q(n.status_text), q(n.profile_theme), q(n.level),
    q(n.xp), q(n.reputation), 'true', ago(n.age_days), 'now()']),
  'on conflict do nothing');
world += '\n' + rows('wallets', ['user_id', 'balance', 'lifetime_earned'],
  w.npcs.map((n) => [q(n.id), q(n.balance), q(n.balance)]), 'on conflict do nothing');
world += '\n' + rows('currency_transactions',
  ['user_id', 'amount', 'balance_after', 'kind', 'description', 'idempotency_key', 'created_at'],
  w.npcs.map((n) => [q(n.id), q(n.balance), q(n.balance), `'signup_bonus'::public.txn_kind`, q('Simulated starting balance'),
    q('npc-seed'), ago(n.age_days)]), 'on conflict do nothing');
world += '\n' + rows('avatars', ['user_id', 'skin_tone', 'body_type', 'height_scale', 'head_scale', 'equipped'],
  w.npcs.map((n) => [q(n.id), q(n.avatar.skin_tone), q(n.avatar.body_type), q(n.avatar.height_scale),
    q(n.avatar.head_scale), j(n.avatar.equipped)]), 'on conflict do nothing');
world += '\n' + rows('inventory_items', ['user_id', 'item_id', 'serial_number', 'acquired_via', 'acquired_at'],
  w.npcs.flatMap((n) => n.inventory.map((i) => [q(n.id), q(i.item_id), q(i.serial_number), q('seed'), ago(i.age_days)])),
  'on conflict do nothing');
world += '\n' + rows('player_game_stats',
  ['user_id', 'game_id', 'plays', 'best_score', 'total_score', 'total_orbs', 'first_played_at', 'last_played_at'],
  w.npcs.flatMap((n) => n.game_stats.map((g) => [q(n.id), q(g.game_id), q(g.plays), q(g.best_score), q(g.total_score),
    q(g.total_orbs), ago(n.age_days), `now() - interval '${g.last_played_hours} hours'`])), 'on conflict do nothing');
world += '\n' + rows('follows', ['follower_id', 'followee_id'], w.follows.map(([a, b]) => [q(a), q(b)]), 'on conflict do nothing');
world += '\n' + rows('friendships', ['user_id', 'friend_id'],
  w.friendships.flatMap(([a, b]) => [[q(a), q(b)], [q(b), q(a)]]), 'on conflict do nothing');
world += '\n' + rows('user_achievements', ['user_id', 'achievement_key'],
  w.npcs.flatMap((n) => n.achievements.map((a) => [q(n.id), q(a)])), 'on conflict do nothing');
world += '\n' + rows('activity_events', ['user_id', 'kind', 'data', 'created_at'],
  w.activity.map((e) => [q(e.user_id), q(e.kind), j(e.data), agoMin(e.minutes_ago)]), '');
world += '\n' + rows('item_price_points', ['item_id', 'day', 'avg_price', 'volume'],
  w.pricePoints.map((p) => [q(p.item_id), `private.today() - ${p.days_ago}`, q(p.avg_price), q(p.volume)]),
  'on conflict do nothing');

writeFileSync(join(OUT, '20261114000010_world.sql'), world);
console.log(`content: ${CATALOG.length} items, ${GAMES.length} games, ${GAME_PASSES.length} passes, ${ACHIEVEMENTS.length} achievements, ${QUESTS.length} quests`);
console.log(`world: ${w.npcs.length} npcs, ${w.follows.length} follows, ${w.friendships.length} friendships, ${w.activity.length} events, ${w.pricePoints.length} price points`);
